def forwards_backfill_existing_rows(apps, schema_editor):
    """Preserve what hand-created rows already meant.

    Two things would otherwise regress silently:

    * ``min_severity`` lived in ``config``; a bare AddField default would discard a
      floor an operator had set to ``critical`` and start paging them on ``high``.
    * every row that exists today authenticates with a **bot token** (webhook mode
      is new in this migration), so the ``webhook_url`` column default is wrong for
      all of them — left uncorrected, the first delivery after deploy would try to
      POST a bot token as if it were a URL and fail permanently.
    """
    DeliveryConnection = apps.get_model("integrations", "DeliveryConnection")
    for row in DeliveryConnection.objects.all().iterator(chunk_size=500):
        config = dict(row.config or {})
        stored = str(config.pop("min_severity", "") or "").strip().lower()
        if stored:
            row.min_severity = stored
            row.config = config
        row.auth_mode = "bot_token"
        row.save(update_fields=["min_severity", "config", "auth_mode"])


def backwards_demote_min_severity(apps, schema_editor):
    """Put the floor back into config so a rollback keeps delivering correctly."""
    DeliveryConnection = apps.get_model("integrations", "DeliveryConnection")
    for row in DeliveryConnection.objects.all().iterator(chunk_size=500):
        config = dict(row.config or {})
        config["min_severity"] = row.min_severity
        row.config = config
        row.save(update_fields=["config"])


