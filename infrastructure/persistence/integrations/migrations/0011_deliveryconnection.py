"""Rename SinkConnector -> DeliveryConnection and productize it (ADR 0016 D2).

Hand-written rather than autogenerated for two reasons: ``makemigrations`` cannot
infer a model rename non-interactively (it would emit delete+create and drop every
existing row), and the ``min_severity`` promotion needs a real backfill —
a bare ``AddField(default="high")`` would silently discard the floor of any
connection an operator had set to ``critical``.
"""

from django.conf import settings
